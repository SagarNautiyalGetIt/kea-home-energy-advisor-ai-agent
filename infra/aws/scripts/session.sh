#!/usr/bin/env bash
# Shared, local-only checks for the manual EC2 Make targets.
set -euo pipefail

KEA_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../../.." && pwd)"
KEA_WORK="$KEA_ROOT/infra/aws/.work"
KEA_SESSION_ENV="$KEA_WORK/session.env"
KEA_STACK="$KEA_ROOT/infra/aws/ec2"
KEA_IP_STACK="$KEA_ROOT/infra/aws/address"
KEA_IP_DIR="$KEA_WORK/elastic-ip"
KEA_IP_STATE="$KEA_IP_DIR/terraform.tfstate"
KEA_ACCOUNT=022499038388
KEA_REGION=ap-southeast-2

kea_require_id() {
  local id="${1:-}"
  [[ "$id" =~ ^[a-z0-9]{8,16}$ ]] || {
    printf 'Set SESSION_ID to the 8–16 character ID from deployment.\n' >&2
    return 1
  }
}

kea_save_session_id() {
  local id="$1" temporary
  kea_require_id "$id"
  umask 077
  mkdir -p "$KEA_WORK"
  temporary="$(mktemp "$KEA_WORK/.session.env.XXXXXX")"
  printf 'export SESSION_ID=%s\n' "$id" > "$temporary"
  mv -f -- "$temporary" "$KEA_SESSION_ENV"
}

kea_current_session_id() {
  local id settings count=0
  if [[ -e "$KEA_SESSION_ENV" || -L "$KEA_SESSION_ENV" ]]; then
    [[ -f "$KEA_SESSION_ENV" && ! -L "$KEA_SESSION_ENV" ]] || {
      echo 'Saved session file is invalid; inspect it before continuing.' >&2
      return 1
    }
    id="$(sed -n 's/^export SESSION_ID=//p' "$KEA_SESSION_ENV")"
    kea_require_id "$id"
    [[ -f "$KEA_WORK/public-$id/operator.env" ]] || {
      echo 'Saved session ID has no local deployment state; inspect it before continuing.' >&2
      return 1
    }
  else
    for settings in "$KEA_WORK"/public-*/operator.env; do
      if [[ -f "$settings" ]]; then
        count=$((count + 1))
        id="${settings%/operator.env}"
        id="${id##*/public-}"
      fi
    done
    if (( count != 1 )); then
      echo 'No unique saved session; specify SESSION_ID explicitly.' >&2
      return 1
    fi
    kea_require_id "$id"
  fi
  printf '%s\n' "$id"
}

kea_clear_session_id() {
  local id="$1" saved
  [[ -f "$KEA_SESSION_ENV" && ! -L "$KEA_SESSION_ENV" ]] || return 0
  saved="$(sed -n 's/^export SESSION_ID=//p' "$KEA_SESSION_ENV")"
  [[ "$saved" == "$id" ]] && rm -- "$KEA_SESSION_ENV"
  return 0
}

kea_load_session() {
  local id="${1:-}"
  kea_require_id "$id"
  local directory="$KEA_WORK/public-$id"
  [[ -f "$directory/operator.env" && ! -L "$directory/operator.env" ]] || {
    printf 'Session settings missing: %s/operator.env\n' "$directory" >&2
    return 1
  }
  # This owner-only file is generated by `make session` and has no secrets.
  # Old sessions predate retained IPs; do not inherit a caller's TF_VAR value.
  unset TF_VAR_elastic_ip_allocation_id TF_VAR_enable_voice_alerts
  source "$directory/operator.env"
  [[ "$SESSION_ID" == "$id" && "$SESSION_DIR" == "$directory" &&
     "$STATE" == "$directory/terraform.tfstate" &&
     "$TF_DATA_DIR" == "$directory/terraform-data" ]] || {
    printf 'Session settings do not match %s\n' "$id" >&2
    return 1
  }
  KEA_SSH=(-i "$SESSION_DIR/id_ed25519"
    -o "UserKnownHostsFile=$SESSION_DIR/known_hosts"
    -o ConnectTimeout=5
    -o StrictHostKeyChecking=accept-new)
  # Ephemeral Terraform input: never write this value to operator.env, state
  # or a saved plan. Load it again for each plan/apply/destroy invocation.
  if [[ -f "$SESSION_DIR/db-master-password" && ! -L "$SESSION_DIR/db-master-password" ]]; then
    export TF_VAR_db_master_password
    TF_VAR_db_master_password="$(cat "$SESSION_DIR/db-master-password")"
  fi
}

kea_check_account() {
  [[ "$AWS_PROFILE" == kea-energy && "$AWS_REGION" == "$KEA_REGION" &&
     "$AWS_DEFAULT_REGION" == "$KEA_REGION" ]] || {
    printf 'Use profile kea-energy in Sydney (%s).\n' "$KEA_REGION" >&2
    return 1
  }
  local actual
  actual="$(aws sts get-caller-identity --profile "$AWS_PROFILE" \
    --region "$KEA_REGION" --query Account --output text)"
  [[ "$actual" == "$KEA_ACCOUNT" ]] || {
    printf 'Wrong AWS account: %s (expected %s).\n' "$actual" "$KEA_ACCOUNT" >&2
    return 1
  }
}

kea_ip_output() {
  TF_DATA_DIR="$KEA_IP_DIR/terraform-data" \
    terraform -chdir="$KEA_IP_STACK" output -state="$KEA_IP_STATE" -raw "$1"
}

kea_ip_details() {
  [[ -s "$KEA_IP_STATE" ]] || {
    echo 'Retained Elastic IP state is missing; run make -C infra/aws ip-allocate first.' >&2
    return 1
  }
  KEA_IP_ALLOCATION_ID="$(kea_ip_output allocation_id)"
  KEA_IP_PUBLIC_IP="$(kea_ip_output public_ip)"
  [[ "$KEA_IP_ALLOCATION_ID" == eipalloc-* &&
     "$KEA_IP_PUBLIC_IP" =~ ^([0-9]{1,3}\.){3}[0-9]{1,3}$ ]] || {
    echo 'Retained Elastic IP state has invalid outputs.' >&2
    return 1
  }
  local actual
  actual="$(aws ec2 describe-addresses --region "$KEA_REGION" \
    --allocation-ids "$KEA_IP_ALLOCATION_ID" --query 'Addresses[0].PublicIp' --output text)"
  [[ "$actual" == "$KEA_IP_PUBLIC_IP" ]] || {
    echo 'Retained Elastic IP state disagrees with the Sydney account.' >&2
    return 1
  }
}

kea_ssh() {
  : "${PUBLIC_IP:?Run make apply-create first}"
  ssh "${KEA_SSH[@]}" "ec2-user@$PUBLIC_IP" "$@"
}

kea_scp() {
  : "${PUBLIC_IP:?Run make apply-create first}"
  scp "${KEA_SSH[@]}" "$@" "ec2-user@$PUBLIC_IP:~/"
}
